# ---------------------------------------------------------------------------
# 3. Context-Aware Polysemy / Homonym Disambiguator
# ---------------------------------------------------------------------------
def disambiguate_homonym(word: str, full_sentence: str) -> Optional[str]:
    """
    Examines the lexical context around polysemous Hindi words (सोना, आम, फल, हार, पत्र, उत्तर, सवा, पास, अपना, पर, तक, तो, है, etc.)
    and returns the accurate contextual Santali translation.
    """
    s = full_sentence.lower()
    w = word.strip().lower()

    if w in ["है"]:
        # Locative/Existential (ᱢᱮᱱᱟᱜᱼᱟ) vs Equative (ᱠᱟᱱᱟ)
        loc_triggers = ["तरफ़", "तरफ", "में", "पर", "पास", "यहाँ", "यहाँ", "वहाँ", "अंदर", "बाहर", "नीचे", "ऊपर"]
        if any(t in s for t in loc_triggers):
            return "ᱢᱮᱱᱟᱜᱼᱟ"
        return "ᱠᱟᱱᱟ"

    elif w in ["पर"]:
        # Meaning 1: Coordinating Conjunction "but/however" (ᱢᱮᱱᱠᱷᱟᱱ)
        # When preceded by comma/punct, at start of clause, or followed by "सच/लेकिन/किन्तु"
        conj_triggers = [", पर", "। पर", "! पर", "; पर", "पर सच", "परन्तु", "पर बात", "पर यह", "पर वो", "पर वह"]
        if any(t in s for t in conj_triggers) or re.search(r'(^|[,;।!?]\s*)पर\b', s):
            return "ᱢᱮᱱᱠᱷᱟᱱ"
        # Meaning 2: Locative/Instrumental Postposition (ᱨᱮ / ᱛᱮ)
        return "ᱨᱮ"

    elif w in ["तक"]:
        # Meaning 1: Emphatic Scalar Particle "not even" (ᱦᱚᱸ)
        # When accompanied by negative markers in the clause (भनक तक नहीं, खबर तक नहीं, एक बार तक नहीं)
        neg_triggers = ["तक नहीं", "तक ना", "तक न", "तक मत", "भनक तक", "खबर तक", "आवाज़ तक"]
        if any(t in s for t in neg_triggers):
            return "ᱦᱚᱸ"
        # Meaning 2: Spatial/Temporal Limit "until/up to" (ᱫᱷᱟᱹᱵᱤᱡ)
        return "ᱫᱷᱟᱹᱵᱤᱡ"

    elif w in ["तो"]:
        # Meaning 1: Conditional "then" (ᱮᱱᱠᱷᱟᱱ)
        if any(c in s for c in ["अगर", "यदि", "जब"]):
            return "ᱮᱱᱠᱷᱟᱱ"
        # Meaning 2: Topic Marker "as for / indeed" (ᱫᱚ / ᱢᱟ)
        topic_triggers = ["तुम तो", "हम तो", "मैं तो", "वह तो", "सच तो", "बात तो", "यह तो", "वो तो"]
        if any(t in s for t in topic_triggers):
            return "ᱫᱚ"
        return "ᱫᱚ"

    elif w in ["सोना", "सोने"]:
        # Meaning 1: Gold (ᱥᱚᱱᱟ / ᱥᱟᱢᱟᱱᱚᱢ)
        gold_triggers = ["महंगा", "सस्ता", "खरीद", "गहना", "गहने", "तोला", "अंगूठी", "हार", "धातु", "दुकान", "भाव", "दाम"]
        if any(t in s for t in gold_triggers):
            return "ᱥᱚᱱᱟ"
        # Meaning 2: Sleep (ᱡᱟᱹᱯᱤᱫ)
        sleep_triggers = ["रात", "चैन", "बिस्तर", "भूल", "नींद", "चाहता", "पसंद", "थक", "सोने गया", "सो गया", "सो रहा"]
        if any(t in s for t in sleep_triggers):
            return "ᱡᱟᱹᱯᱤᱫ"

    elif w in ["पास"]:
        # Meaning 1: Official Approval / Passed (ᱯᱟᱥ / ᱯᱟᱥ ᱚᱪᱚ)
        approval_triggers = ["फ़ाइल", "फाइल", "करवाई", "करवाया", "कराई", "कराया", "करवाना", "बिल", "प्रस्ताव", "परीक्षा", "नक्शा", "निगम", "पास होना", "पास करना"]
        if any(t in s for t in approval_triggers):
            return "ᱯᱟᱥ"
        # Meaning 2: Near / Proximity / Possession (ᱥᱩᱨ / ᱴᱷᱮᱱ)
        return "ᱥᱩᱨ"

    elif w in ["अपना", "अपनी", "अपने"]:
        # Contextual Reflexive Agreement based on Subject Person
        # 2nd Person Subject: तुम, तुमने, आप, आपने, तू -> ᱟᱢᱟᱜ
        if any(p in s for p in ["तुमने", "तुम", "आप", "आपने", "तू"]):
            return "ᱟᱢᱟᱜ"
        # 1st Person Subject: मैं, मैंने -> ᱤᱧᱟᱜ, हम, हमने -> ᱟᱞᱮᱭᱟᱜ
        elif any(p in s for p in ["मैंने", "मैं"]):
            return "ᱤᱧᱟᱜ"
        elif any(p in s for p in ["हमने", "हम"]):
            return "ᱟᱞᱮᱭᱟᱜ"
        # 3rd Person Plural: वे, उन्होंने, लोगों ने -> ᱩᱱᱠᱩᱣᱟᱜ
        elif any(p in s for p in [" उन्होंने", "वे", "उन लोगों"]):
            return "ᱩᱱᱠᱩᱣᱟᱜ"
        # 3rd Person Singular Default: वह, उसने -> ᱟᱡᱟᱜ
        return "ᱟᱡᱟᱜ"

    elif w in ["आम", "आमो", "आमों"]:
        # Meaning 1: Common / Ordinary (ᱥᱟᱫᱷᱟᱨᱚᱱ)
        common_triggers = ["बात", "आदमी", "लोग", "तौर", "जनता", "नागरिक", "जीवन", "मुद्दे"]
        if any(t in s for t in common_triggers):
            return "ᱥᱟᱫᱷᱟᱨᱚᱱ"
        # Meaning 2: Mango (ᱩᱞ)
        mango_triggers = ["मीठे", "मीठा", "कच्चे", "कच्चा", "पके", "पका", "पेड़", "फल", "मौसम", "खाना", "खाओ", "पेड़ पर", "बगीचा", "अचार"]
        if any(t in s for t in mango_triggers):
            return "ᱩᱞ"

    elif w in ["फल", "फलों"]:
        # Meaning 1: Karma / Result / Consequence (ᱠᱩᱲᱟᱹᱭ)
        karma_triggers = ["मेहनत", "कर्म", "सब्र", "काम का", "परीक्षा का", "सफलता का", "कठिन"]
        if any(t in s for t in karma_triggers):
            return "ᱠᱩᱲᱟᱹᱭ"
        # Meaning 2: Fruit (ᱡᱚ)
        fruit_triggers = ["ताज़ा", "ताजा", "मीठा", "मीठे", "खाओ", "खाना", "पेड़", "तोड़ना", "बाजार", "सेब", "केला", "अंगूर"]
        if any(t in s for t in fruit_triggers):
            return "ᱡᱚ"

    elif w in ["हार", "हारने", "हारना"]:
        # Meaning 1: Defeat (ᱦᱟᱨᱟᱣ)
        defeat_triggers = ["मानी", "मानना", "जीत", "खेल", "चुनाव", "मैच", "प्रतियोगिता", "स्वीकार"]
        if any(t in s for t in defeat_triggers):
            return "ᱦᱟᱨᱟᱣ"
        # Meaning 2: Garland / Necklace (ᱢᱟᱞᱟ)
        garland_triggers = ["फूल", "फूलों", "सोने", "गले", "पहनाया", "पहना", "सुंदर हार", "मोती"]
        if any(t in s for t in garland_triggers):
            return "ᱢᱟᱞᱟ"

    elif w in ["पत्र", "पत्रों", "पत्ते", "पत्ता"]:
        # Meaning 1: Letter / Mail (ᱪᱤᱴᱷᱤ)
        letter_triggers = ["लिखा", "लिखना", "पढ़ना", "भेजा", "डाक", "डाकिया", "पोस्ट", "समाचार"]
        if any(t in s for t in letter_triggers):
            return "ᱪᱤᱴᱷᱤ"
        # Meaning 2: Leaf (ᱥᱟᱠᱟᱢ)
        leaf_triggers = ["पेड़", "तोड़ना", "हरा", "हरे", "सूखा", "सूखे", "शाखा", "पौधा", "झड़", "गिर"]
        if any(t in s for t in leaf_triggers):
            return "ᱥᱟᱠᱟᱢ"

    elif w in ["उत्तर"]:
        # Meaning 1: North direction (ᱮᱛᱚᱢ)
        north_triggers = ["दिशा", "भारत", "की ओर", "दक्षिण", "पूर्व", "पश्चिम", "ध्रुव", "पर्वत"]
        if any(t in s for t in north_triggers):
            return "ᱮᱛᱚᱢ"
        # Meaning 2: Answer / Reply (ᱛᱮᱞᱟ)
        answer_triggers = ["सवाल", "प्रश्न", "दो", "दिया", "सही", "गलत", "पूछा", "लिखो", "जवाब"]
        if any(t in s for t in answer_triggers):
            return "ᱛᱮᱞᱟ"

    elif w in ["सवा"]:
        # Meaning 1: Time (Quarter past)
        if "बजे" in s or "बजकर" in s or "समय" in s:
            return "ᱥᱟᱣᱟ"
        # Meaning 2: Quantity (1.25)
        return "ᱥᱟᱣᱟ"

    elif w in ["कल"]:
        # Split sentence into clauses so tense markers in other clauses (e.g. मिलेगा in clause 2)
        # do not leak into the clause where कल resides (e.g. चले गए in clause 1)
        clauses = re.split(r'[,;।!?]|\bक्योंकि\b|\bइसलिए\b|\bकि\b|\bलेकिन\b|\bअगर\b|\bतो\b', full_sentence)
        target_clause = ""
        for c in clauses:
            if re.search(r'\bकल\b', c):
                target_clause = c.lower()
                break
        if not target_clause:
            target_clause = s

        past_indicators = [
            "गए", "गया", "गयी", "गई", "थी", "था", "थे", "हुई थी", "हुआ था", "हुआ", "हुई",
            "किया", "लगा", "लिया", "दी", "दिया", "पहुँचा", "पहुंचा", "देखा", "सुना", "बोला", "बीता"
        ]
        future_indicators = [
            "गा", "गी", "गे", "जाएगा", "जाएगी", "जाएंगे", "करेगा", "करेगी", "करेंगे",
            "होगी", "होगा", "होंगे", "रहेगा", "रहेगी", "रहेंगे", "मिलेगा", "मिलेगी", "आने वाला"
        ]
        
        has_past = any(re.search(r'\b' + re.escape(p) + r'\b', target_clause) or p in target_clause for p in past_indicators)
        has_future = any(re.search(r'\b' + re.escape(f) + r'\b', target_clause) or f in target_clause for f in future_indicators)
        
        if has_past and not has_future:
            return "ᱦᱚᱞᱟ"
        elif has_future and not has_past:
            return "ᱜᱟᱯᱟ"
        elif has_past:
            return "ᱦᱚᱞᱟ"
        return "ᱜᱟᱯᱟ"

    return None

# ---------------------------------------------------------------------------
# 4. Universal Morphological & Participle Rule Engine
# ---------------------------------------------------------------------------
def apply_morphological_verb_rules(token: str, lexicon: Dict[str, str]) -> Optional[str]:
    """
    Transforms inflected Hindi verbs into their exact Santali morpho-syntactic equivalent.
    Supports complex causative morphology, 2nd-person future light verbs (-लोगे), and particle-split perfect verbs.
    """
    w = token.strip().rstrip("।,!?.")
    if not w:
        return None

    def clean_root(val: str) -> str:
        return val.split('/')[0].strip() if val else ""

    # Causative Root Map for common irregular Hindi causative stems
    causative_stem_map = {
        "तुड़": "ᱨᱟᱹᱯᱩᱫ", "तोड़": "ᱨᱟᱹᱯᱩᱫ", "बन": "ᱵᱮᱱᱟᱣ", "उठ": "ᱨᱟᱠᱟᱵ",
        "कर": "ᱠᱚᱨᱟᱣ", "ᱥᱮᱪᱮᱫ": "ᱪᱮᱫ", "सिख": "ᱪᱮᱫ", "पिला": "ᱧᱩ",
        "खिला": "ᱡᱚᱢ", "सुला": "ᱡᱟᱹᱯᱤᱫ", "दौड़ा": "ᱫᱟᱹᱲ", "बैठा": "ᱫᱩᱲᱩᱵ",
        "जगा": "ᱵᱮᱨᱮᱫ", "हंसा": "ᱞᱟᱸᱫᱟ", "हँसा": "ᱞᱟᱸᱫᱟ", "रुला": "ᱨᱟᱜ",
        "पढ़ा": "ᱯᱟᱲᱦᱟᱣ", "लिख": "ᱚᱞ", "कट": "ᱜᱮᱫ", "धुल": "ᱟᱹᱨᱩᱵ",
        "पहुँच": "ᱥᱮᱴᱮᱨ", "पहुंच": "ᱥᱮᱴᱮᱨ", "दिख": "ᱧᱮᱞ", "सुना": "ᱟᱧᱡᱚᱢ"
    }

    # 1. Split Perfect / Emphatic Verb Compounds (e.g. हुआ भी है -> ᱦᱩᱭ ᱦᱚᱸ ᱦᱩᱭ ᱟᱠᱟᱱᱟ)
    if w in ["हुआ भी है", "हुई भी है", "हुए भी हैं", "हुआ भी है।"]:
        return "ᱦᱩᱭ ᱦᱚᱸ ᱦᱩᱭ ᱟᱠᱟᱱᱟ"
    if w in ["किया भी है", "की भी है", "किए भी हैं"]:
        return "ᱠᱚᱨᱟᱣ ᱦᱚᱸ ᱠᱚᱨᱟᱣ ᱟᱠᱟᱱᱟ"

    # 2. Conjunct Verbs (e.g. हाथ खड़े कर दिए -> ᱛᱤ ᱠᱚ ᱛᱩᱞ ᱠᱮᱫᱼᱟ)
    if "हाथ खड़े कर दिए" in w or "हाथ खड़े कर दिए।" in w or "हाथ खड़े कर दिये" in w:
        return "ᱛᱤ ᱠᱚ ᱛᱩᱞ ᱠᱮᱫᱼᱟ"
    if "हाथ खड़े करना" in w or "हाथ खड़े" in w:
        return "ᱛᱤ ᱛᱩᱞ"

    # 3. Present Perfect Compound Verbs: <Stem> + गई है / गया है / गए हैं (e.g. हो गई है -> ᱦᱩᱭ ᱟᱠᱟᱱᱟ)
    if any(w.endswith(end) for end in ["हो गई है", "हो गया है", "हो गए हैं", "गई है", "गया है", "गए हैं", "गई हैं"]):
        v_stem = re.sub(r'(हो\s+)?(गई|गया|गए|गईं)\s+है(ं)?', '', w).strip()
        raw = lexicon.get(v_stem) or lexicon.get(v_stem + "ना") or "ᱦᱩᱭ"
        root = clean_root(raw)
        return f"{root} ᱟᱠᱟᱱᱟ"

    # 4. Adjectival Particle -वाला/-वाली/-वाले (e.g. अटके वाली -> ᱟᱴᱠᱟᱣ ᱞᱮᱠᱟᱱ, अटकने वाली -> ᱟᱴᱠᱟᱣ ᱞᱮᱠᱟᱱ)
    if any(w.endswith(end) for end in ["वाली", "वाला", "वाले"]) and len(w) > 4:
        v_stem = re.sub(r'(वाली|वाला|वाले)$', '', w).strip()
        raw = lexicon.get(v_stem) or lexicon.get(v_stem + "ना") or lexicon.get(v_stem + "ा")
        root = clean_root(raw)
        if root:
            return f"{root} ᱞᱮᱠᱟᱱ"

    # 5. Future 2nd-Person Auxiliary Light Verbs: <Stem> + लोगे (e.g. झाड़ लोगे, कर लोगे, देख लोगे, ले लोगे)
    # NEVER confuse with noun लोग (people = ᱦᱚᱲ ᱠᱚ)!
    if "झाड़ लोगे" in w or "पल्ला झाड़ लोगे" in w:
        return "ᱯᱷᱟᱨᱟᱠᱚᱜᱼᱟ"
    if w.endswith("लोगे") and len(w) > 4:
        v_stem = w[:-4].strip()
        raw = lexicon.get(v_stem) or lexicon.get(v_stem + "ना") or lexicon.get(v_stem + "ा")
        root = clean_root(raw)
        if root:
            return f"{root}ᱚᱜᱼᱟ"

    # 3. Causative Conjunctive Participle: -वाकर / -वाके (e.g. तुड़वाकर -> ᱨᱟᱹᱯᱩᱫ ᱚᱪᱚ ᱠᱟᱛᱮ)
    if (w.endswith("वाकर") or w.endswith("वाके") or w.endswith("वा कर")) and len(w) > 4:
        c_stem = w.replace("वाकर", "").replace("वाके", "").replace("वा कर", "").strip()
        root = causative_stem_map.get(c_stem) or clean_root(lexicon.get(c_stem) or lexicon.get(c_stem + "ना"))
        if root:
            return f"{root} ᱚᱪᱚ ᱠᱟᱛᱮ"

    # 4. Causative Past / Anterior: -वाया / -वाई / -वाए / -वायी (e.g. बनवाया था -> ᱵᱮᱱᱟᱣ ᱚᱪᱚ ᱞᱮᱫᱼᱟ)
    if any(w.endswith(end) for end in ["वाया था", "वाई थी", "वाए थे", "वाया", "वाई", "वाए", "वायी"]):
        is_anterior = "था" in w or "थी" in w or "थे" in w
        c_stem = re.sub(r'वा[यायीएे]\s*(था|थी|थे)?', '', w).strip()
        root = causative_stem_map.get(c_stem) or clean_root(lexicon.get(c_stem) or lexicon.get(c_stem + "ना"))
        if root:
            return f"{root} ᱚᱪᱚ ᱞᱮᱫᱼᱟ" if is_anterior else f"{root} ᱚᱪᱚ ᱠᱮᱫᱼᱟ"

    # 5. Causative Infinitive: -वाना / -वानी / -वाने (e.g. तुड़वाना -> ᱨᱟᱹᱯᱩᱫ ᱚᱪᱚ)
    if (w.endswith("वाना") or w.endswith("वानी") or w.endswith("वाने")) and len(w) > 4:
        c_stem = w[:-4].strip()
        root = causative_stem_map.get(c_stem) or clean_root(lexicon.get(c_stem) or lexicon.get(c_stem + "ना"))
        if root:
            return f"{root} ᱚᱪᱚ"

    # 6. Standard Conjunctive Participle: <Stem> + कर / के (e.g. खरीदकर -> ᱠᱤᱨᱤᱧ ᱠᱟᱛᱮ, खाकर -> ᱡᱚᱢ ᱠᱟᱛᱮ)
    if len(w) > 3 and (w.endswith("कर") or w.endswith("के")):
        suffix_len = 2
        v_stem = w[:-suffix_len]
        raw = lexicon.get(v_stem) or lexicon.get(v_stem + "ना") or lexicon.get(v_stem + "ा")
        root = clean_root(raw)
        if root:
            return f"{root} ᱠᱟᱛᱮ"

    # 7. Simultaneous Participle: <Stem> + ते हुए / ती हुई (e.g. भागते हुए -> ᱫᱟᱹᱲ ᱛᱩᱞᱩᱡ, मुस्कुराते हुए -> ᱢᱩᱞᱩᱡ ᱞᱟᱸᱫᱟ ᱛᱩᱞᱩᱡ)
    if "ते हुए" in w or "ती हुई" in w or "ते-ते" in w:
        v_stem = w.replace("ते हुए", "").replace("ती हुई", "").replace("ते-ते", "").strip()
        raw = lexicon.get(v_stem) or lexicon.get(v_stem + "ना")
        root = clean_root(raw)
        if root:
            return f"{root} ᱛᱩᱞᱩᱡ"

    # 8. Specific Causative Lexical Mappings
    causative_map = {
        "पिलाना": "ᱧᱩ ᱦᱚᱪᱚ", "पिलाकर": "ᱧᱩ ᱦᱚᱪᱚ ᱠᱟᱛᱮ", "पिलाया": "ᱧᱩ ᱦᱚᱪᱚ ᱠᱮᱫᱼᱟ",
        "खिलाना": "ᱡᱚᱢ ᱦᱚᱪᱚ", "खिलाकर": "ᱡᱚᱢ ᱦᱚᱪᱚ ᱠᱟᱛᱮ", "खिलाया": "ᱡᱚᱢ ᱦᱚᱪᱚ ᱠᱮᱫᱼᱟ",
        "सुलाना": "ᱡᱟᱹᱯᱤᱫ ᱦᱚᱪᱚ", "सुलाकर": "ᱡᱟᱹᱯᱤᱫ ᱦᱚᱪᱚ ᱠᱟᱛᱮ", "सुला दिया": "ᱡᱟᱹᱯᱤᱫ ᱦᱚᱪᱚ ᱠᱮᱫᱮᱭᱟᱭ",
        "हँसाना": "ᱞᱟᱸᱫᱟ ᱦᱚᱪᱚ", "हंसाना": "ᱞᱟᱸᱫᱟ ᱦᱚᱪᱚ", "रुलाना": "ᱨᱟᱜ ᱦᱚᱪᱚ",
        "सिखाना": "ᱪᱮᱫ ᱦᱚᱪᱚ", "पढ़ाना": "ᱯᱟᱲᱦᱟᱣ ᱦᱚᱪᱚ", "दौड़ाना": "ᱫᱟᱹᱲ ᱦᱚᱪᱚ",
        "बैठाना": "ᱫᱩᱲᱩᱵ ᱦᱚᱪᱚ", "जगाना": "ᱵᱮᱨᱮᱫ ᱦᱚᱪᱚ", "कराना": "ᱠᱟᱹᱢᱤ ᱦᱚᱪᱚ",
    }
    if w in causative_map:
        return causative_map[w]

    # 9. Future Tense Inflections (-एगा / -एगी / -एंगे)
    if len(w) > 3 and (w.endswith("एगा") or w.endswith("एगी")):
        v_stem = w[:-3]
        raw = lexicon.get(v_stem) or lexicon.get(v_stem + "ना") or lexicon.get(v_stem + "ा")
        root = clean_root(raw)
        if root:
            return f"{root}ᱟ"

    if len(w) > 3 and w.endswith("एंगे"):
        v_stem = w[:-4]
        raw = lexicon.get(v_stem) or lexicon.get(v_stem + "ना") or lexicon.get(v_stem + "ा")
        root = clean_root(raw)
        if root:
            return f"ᱠᱚ {root}ᱟ"

    # 10. Passive Continuous: <Stem> + या जा रहा है (e.g. बनाया जा रहा है -> ᱵᱮᱱᱟᱣ ᱦᱩᱭᱩᱜ ᱠᱟᱱᱟ)
    if "जा रहा है" in w or "जा रही है" in w:
        v_stem = w.replace("जा रहा है", "").replace("जा रही है", "").replace("या", "").strip()
        raw = lexicon.get(v_stem) or lexicon.get(v_stem + "ना") or lexicon.get(v_stem + "ा")
        root = clean_root(raw)
        if root:
            return f"{root} ᱦᱩᱭᱩᱜ ᱠᱟᱱᱟ"

    # 11. Modal "सकता है / सकती है" (Can/Ability): <Stem> + ᱫᱟᱲᱮᱭᱟᱜᱼᱟ
    if w.endswith("सकता है") or w.endswith("सकती है") or w.endswith("सकते हैं"):
        v_stem = re.sub(r'सकᱛ[ाीᱮ] [ᱦह][ैंै]', '', w).strip()
        raw = lexicon.get(v_stem) or lexicon.get(v_stem + "ना")
        root = clean_root(raw)
        if root:
            return f"{root} ᱫᱟᱲᱮᱭᱟᱜᱼᱟ"

    # 12. Modal "चाहिए" (Should/Must): <Stem> + ᱞᱟᱹᱠᱛᱤ ᱠᱟᱱᱟ
    if w.endswith("चाहिए"):
        v_stem = w[:-5].strip()
        raw = lexicon.get(v_stem) or lexicon.get(v_stem + "ना")
        root = clean_root(raw)
        if root:
            return f"{root} ᱞᱟᱹᱠᱛᱤ ᱠᱟᱱᱟ"

    # 13. Modal "चाहता है / चाहती है" (Wants): <Stem> + ᱥᱟᱱᱟᱭᱮ ᱠᱟᱱᱟ
    if w.endswith("चाहता है") or w.endswith("चाहती है") or w.endswith("चाहते हैं"):
        v_stem = re.sub(r'चाहᱛ[ाीᱮ] [ᱦह][ैंै]', '', w).strip()
        raw = lexicon.get(v_stem) or lexicon.get(v_stem + "ना")
        root = clean_root(raw)
        if root:
            return f"{root} ᱥᱟᱱᱟᱭᱮ ᱠᱟᱱᱟ"

    return None
